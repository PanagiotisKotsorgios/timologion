/**
 * User-facing guides — the source of truth for /guides.
 *
 * Each guide is a section of the user documentation. Sections may
 * optionally embed a small `uiPreview` — a deterministic HTML mockup
 * of the UI element referenced in the text (button, toolbar row,
 * card header). Mockups are preferred over screenshot files because
 * they stay in sync with the app's design tokens automatically.
 *
 * When adding a new guide, append to the array and give it the next
 * two-digit `n`. Never renumber existing guides — the number appears
 * in printed PDFs and shouldn't shift under a reader.
 */

/**
 * Optional inline UI mockup. Rendered as a small card that visually
 * imitates the referenced UI. `kind` picks the template:
 *
 *   button — a single primary/secondary button preview
 *   toolbar — a row of buttons or breadcrumb-like segments
 *   card — a titled card with a body paragraph and optional badge
 *   stat — a large-number stat tile like the dashboard KPI cards
 *   field — a labeled form field with placeholder + hint
 *   note — an inline muted callout (e.g. status banner)
 */
export type UiPreview =
  | { kind: "button"; label: string; tone?: "primary" | "secondary" | "danger" | "success" }
  | { kind: "toolbar"; items: { label: string; tone?: "primary" | "muted" | "danger" | "success" }[] }
  | { kind: "card"; title: string; body: string; badge?: string; badgeTone?: "success" | "warning" | "muted" }
  | { kind: "stat"; label: string; value: string; hint?: string; tone?: "brand" | "emerald" | "amber" }
  | { kind: "field"; label: string; placeholder: string; hint?: string; required?: boolean }
  | { kind: "note"; body: string; tone?: "info" | "warning" | "success" | "danger" };

export type GuideSection = {
  heading: string;
  body: string; // paragraphs separated by \n\n
  bullets?: string[];
  tip?: string;
  /** Optional visual — rendered right below the section body. */
  preview?: UiPreview;
};

